/// Age-based vaccine records transcribed from the WHO/UNICEF country
/// schedule viewer (country reports submitted through the JRF).
///
/// These are reminders, not a replacement for the child's official vaccine
/// card. Product combinations and eligibility vary by country and by child.
class VaccineScheduleDose {
  final int ageMonths;
  final String code;
  final String? timingNote;
  final int? daysAfterBirth;
  final String? ageLabelOverride;
  final bool conditional;

  const VaccineScheduleDose(
    this.ageMonths,
    this.code, {
    this.timingNote,
    this.daysAfterBirth,
    this.ageLabelOverride,
    this.conditional = false,
  });

  String get id => '$ageMonths-$code';
}

