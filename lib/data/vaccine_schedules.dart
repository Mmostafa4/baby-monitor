String whoScheduleUrl(String country) {
  final code = vaccineCountryCodes[country] ?? 'EGY';
  return 'https://immunizationdata.who.int/global/wiise-detail-page/vaccination-schedule-for-country_name?ISO_3_CODE=' + code;
}

